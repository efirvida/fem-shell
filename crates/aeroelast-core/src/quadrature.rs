/// Hammer 3-point rule on reference triangle (r+s ≤ 1): degree 2.
///
/// Points: (1/6,1/6), (2/3,1/6), (1/6,2/3), each weight 1/3.
#[inline(always)]
pub fn hammer_tri_3pt() -> QuadratureRule<3, 2> {
    QuadratureRule {
        points: [
            [1.0/6.0, 1.0/6.0],
            [2.0/3.0, 1.0/6.0],
            [1.0/6.0, 2.0/3.0],
        ],
        weights: [1.0/3.0, 1.0/3.0, 1.0/3.0],
    }
}

